"""
Appearance matching — telling *that* backpack from *a* backpack.

This is the hard half of the object problem. YOLO says "backpack". This module
says "the same backpack as the one in file 14".

**Why CLIP alone is not enough, and what we do about it.**

CLIP embeddings encode *semantics* — what kind of thing this is, roughly what it
looks like, what setting it is in. That makes them excellent at "find me photos
of a backpack" and mediocre at "find me photos of *this* backpack". Two different
black backpacks against similar backgrounds will score high. Relying on CLIP
alone here would produce confident matches between unrelated objects, which in an
investigation means a fabricated link between two people.

So instance matching combines two independent signals:

* **CLIP embedding** — shape, type, texture, general appearance.
* **HSV colour histogram** — the actual colours present, and in what proportion.

Colour is where CLIP is weakest and where distinctive objects differ most. A
bright patterned bag and a plain black one are near-identical to CLIP's notion of
"backpack" and wildly different by histogram. Requiring both to agree is what
makes the match mean something.

This is also why the data guide insists the demo object be visually distinctive:
two plain black bags are genuinely indistinguishable by any method here, and the
honest failure is to say so rather than to match them anyway.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any

import numpy as np

logger = logging.getLogger(__name__)

#: CLIP ViT-B/32 — ~600 MB. The large variant (ViT-L/14, ~1.7 GB) would not fit
#: alongside InsightFace and YOLO on a 6 GB card, and buys little for crop
#: matching.
CLIP_MODEL = "openai/clip-vit-base-patch32"

# --------------------------------------------------------------------------
# Matching rule — CONJUNCTIVE, and that choice is measured, not assumed
# --------------------------------------------------------------------------
#
# The first implementation blended the two signals into a weighted sum. Measured
# on 17 same-object pairs and 66 different-object-same-class pairs, that was
# clearly the wrong shape:
#
#     weighted sum @ 0.70      12/66 false matches  (18%)
#     CLIP alone   @ 0.70      47/66 false matches  (71%)
#     clip>=0.94 AND col>=0.35  0/66 false matches, 82% recall
#
# A blend lets a very high CLIP score paper over a poor colour match — which is
# exactly the failure that fabricates a link between two people. Requiring BOTH
# signals to clear their own bar removes that.
#
# The 71% figure is worth keeping in mind: CLIP on its own is close to useless
# for instance matching. It is a semantic embedding; "backpack" dominates
# "*this* backpack".
#
# ---- HONEST LIMIT OF THIS CALIBRATION -------------------------------------
# The same-object pairs were generated by shifting and brightening a crop of the
# SAME photograph. Real same-object pairs — different day, angle, distance,
# lighting — will score materially lower on CLIP, so these thresholds are
# probably too strict for live data and will need lowering.
#
# Conversely the different-object pairs were cars, which are a pathological case
# for colour (most are white, silver, grey or black). A brightly patterned bag
# will separate far better.
#
# Re-measure with `python -m acpia.cli calibrate-objects <dir>` once real
# footage exists. The conjunctive STRUCTURE is validated; the NUMBERS are not.

#: Both must be cleared to treat two sightings as the same physical object.
#: A false merge here invents contact between two people, so this stays strict.
#: 0.94/0.35 was chosen over 0.93/0.40 because the sweep showed identical recall
#: (82%) with zero false merges instead of one.
CLIP_STRONG = 0.94
COLOUR_STRONG = 0.35

#: Both must be cleared to report a *possible* match. Never merges identity —
#: produces a "resembles, needs corroboration" claim the planner must follow up.
CLIP_WEAK = 0.86
COLOUR_WEAK = 0.28

#: Reporting weights only. Used to produce a single readable number for claim
#: text and ranking; the accept/reject decision is conjunctive, never this.
CLIP_WEIGHT = 0.6
COLOUR_WEIGHT = 0.4

#: Crops smaller than this are too coarse for a trustworthy instance match.
MIN_CROP_PX = 32

#: Pixels of context kept around a detection — a little background helps CLIP,
#: too much and we start matching the scene rather than the object.
CROP_MARGIN = 0.08

_CLIP: tuple[Any, Any] | None = None


def get_clip() -> tuple[Any, Any]:
    """Load CLIP once. Downloads ~600 MB on first call."""
    global _CLIP
    if _CLIP is None:
        import torch
        from transformers import CLIPModel, CLIPProcessor

        device = "cuda" if torch.cuda.is_available() else "cpu"
        model = CLIPModel.from_pretrained(CLIP_MODEL).to(device).eval()
        processor = CLIPProcessor.from_pretrained(CLIP_MODEL)
        _CLIP = (model, processor)
        logger.info("CLIP %s ready on %s", CLIP_MODEL, device)
    return _CLIP


def release_clip() -> None:
    """Drop CLIP so its VRAM can be reclaimed."""
    global _CLIP
    _CLIP = None


# --------------------------------------------------------------------------
# Signatures
# --------------------------------------------------------------------------


@dataclass
class AppearanceSignature:
    """What we store to recognise one specific object again."""

    clip: np.ndarray  # L2-normalised CLIP image embedding
    colour: np.ndarray  # normalised HSV histogram
    width: int
    height: int

    @property
    def is_small(self) -> bool:
        return min(self.width, self.height) < MIN_CROP_PX


def crop_region(image: np.ndarray, bbox: tuple[int, int, int, int]) -> np.ndarray | None:
    """Crop a detection with a little margin. Returns None if unusably small."""
    height, width = image.shape[:2]
    x1, y1, x2, y2 = bbox

    margin_x = int((x2 - x1) * CROP_MARGIN)
    margin_y = int((y2 - y1) * CROP_MARGIN)
    x1 = max(0, x1 - margin_x)
    y1 = max(0, y1 - margin_y)
    x2 = min(width, x2 + margin_x)
    y2 = min(height, y2 + margin_y)

    if x2 - x1 < 8 or y2 - y1 < 8:
        return None
    return image[y1:y2, x1:x2]


def colour_histogram(crop: np.ndarray, bins: tuple[int, int] = (16, 8)) -> np.ndarray:
    """Normalised 2-D hue/saturation histogram.

    Hue and saturation only — value (brightness) is dropped deliberately, so the
    same object photographed in bright sun and in shade still matches.
    """
    import cv2

    hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
    hist = cv2.calcHist([hsv], [0, 1], None, list(bins), [0, 180, 0, 256])
    cv2.normalize(hist, hist, 0, 1, cv2.NORM_MINMAX)
    return hist.flatten().astype(np.float32)


def clip_embedding(crop: np.ndarray) -> np.ndarray:
    """L2-normalised CLIP image embedding for a BGR crop."""
    import cv2
    import torch
    from PIL import Image

    model, processor = get_clip()
    device = next(model.parameters()).device

    pil = Image.fromarray(cv2.cvtColor(crop, cv2.COLOR_BGR2RGB))
    inputs = processor(images=pil, return_tensors="pt").to(device)

    with torch.no_grad():
        features = model.get_image_features(**inputs)
        features = features / features.norm(p=2, dim=-1, keepdim=True)

    return features[0].cpu().numpy().astype(np.float32)


def signature_for(image: np.ndarray, bbox: tuple[int, int, int, int]) -> AppearanceSignature | None:
    """Build a full appearance signature for one detected region."""
    crop = crop_region(image, bbox)
    if crop is None:
        return None
    return AppearanceSignature(
        clip=clip_embedding(crop),
        colour=colour_histogram(crop),
        width=crop.shape[1],
        height=crop.shape[0],
    )


# --------------------------------------------------------------------------
# Comparison
# --------------------------------------------------------------------------


@dataclass
class AppearanceMatch:
    """How similar two objects are, with the components kept separate.

    Both parts are reported so a claim can explain *why* two things matched —
    "same shape and same colours" is auditable, a single blended number is not.
    """

    identity: str | None
    combined: float
    clip_similarity: float
    colour_similarity: float
    strong: bool

    @property
    def matched(self) -> bool:
        return self.identity is not None

    def describe(self) -> str:
        if not self.matched:
            return f"no instance match (best {self.combined:.3f})"
        strength = "strong" if self.strong else "possible"
        return (
            f"{strength} match {self.combined:.3f} "
            f"(shape/type {self.clip_similarity:.2f}, colour {self.colour_similarity:.2f})"
        )


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    a = np.asarray(a, dtype=np.float32).ravel()
    b = np.asarray(b, dtype=np.float32).ravel()
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


def compare(a: AppearanceSignature, b: AppearanceSignature) -> tuple[float, float, float]:
    """Compare two signatures. Returns (combined, clip_similarity, colour_similarity)."""
    clip_similarity = _cosine(a.clip, b.clip)

    # Histogram intersection: how much of the colour distribution is shared.
    # More forgiving than correlation when one crop includes extra background.
    colour_similarity = float(np.minimum(a.colour, b.colour).sum() / max(a.colour.sum(), 1e-6))
    colour_similarity = min(colour_similarity, 1.0)

    combined = CLIP_WEIGHT * clip_similarity + COLOUR_WEIGHT * colour_similarity
    return combined, clip_similarity, colour_similarity


def passes_strong(clip_similarity: float, colour_similarity: float) -> bool:
    return clip_similarity >= CLIP_STRONG and colour_similarity >= COLOUR_STRONG


def passes_weak(clip_similarity: float, colour_similarity: float) -> bool:
    return clip_similarity >= CLIP_WEAK and colour_similarity >= COLOUR_WEAK


def match_signature(
    signature: AppearanceSignature,
    candidates: list[tuple[str, AppearanceSignature]],
) -> AppearanceMatch:
    """Best instance match among candidates, using the conjunctive rule.

    Ranks by combined score for readability, but accepts only on BOTH signals
    independently clearing their thresholds.
    """
    best = AppearanceMatch(None, 0.0, 0.0, 0.0, False)
    best_identity: str | None = None
    best_clip = best_colour = best_combined = 0.0

    for identity, candidate in candidates:
        combined, clip_similarity, colour_similarity = compare(signature, candidate)
        if combined > best_combined:
            best_combined = combined
            best_clip = clip_similarity
            best_colour = colour_similarity
            best_identity = identity

    if best_identity is None or not passes_weak(best_clip, best_colour):
        # Report the best score even on rejection — a near miss is worth seeing.
        return AppearanceMatch(None, best_combined, best_clip, best_colour, False)

    return AppearanceMatch(
        identity=best_identity,
        combined=best_combined,
        clip_similarity=best_clip,
        colour_similarity=best_colour,
        strong=passes_strong(best_clip, best_colour),
    )


# --------------------------------------------------------------------------
# Serialisation
# --------------------------------------------------------------------------


def signature_to_bytes(signature: AppearanceSignature) -> bytes:
    """Pack both vectors into one blob: [clip_len:int32][clip][colour]."""
    clip = np.asarray(signature.clip, dtype=np.float32)
    colour = np.asarray(signature.colour, dtype=np.float32)
    header = np.array([clip.size], dtype=np.int32)
    return header.tobytes() + clip.tobytes() + colour.tobytes()


def signature_from_bytes(raw: bytes, width: int = 0, height: int = 0) -> AppearanceSignature:
    clip_len = int(np.frombuffer(raw[:4], dtype=np.int32)[0])
    offset = 4 + clip_len * 4
    clip = np.frombuffer(raw[4:offset], dtype=np.float32)
    colour = np.frombuffer(raw[offset:], dtype=np.float32)
    return AppearanceSignature(clip=clip, colour=colour, width=width, height=height)
